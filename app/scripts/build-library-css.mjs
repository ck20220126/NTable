import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';

// Vite owns PostCSS. Resolve its existing dependency without adding a package.
const require = createRequire(import.meta.url);
const postcss = createRequire(require.resolve('vite/package.json'))('postcss');
export const scope = ':where(.ntable, .ntable-scope, .ntable-portal)';
const demoClass = /^\.(?:demo-storage-status|app-shell|topbar(?:-left|-right)?|workspace(?:-name|-titlebar|-title)?|crumb|base-mark|save-state|share-button|top-action|avatar|sidebar(?:-search|-new)?|nav-item|nav-more|editor-[\w-]+|form-grid|person-avatar|attachment-cell)(?=[\s.:#>+~[]|$)/;
const sources = ['styles.css', 'overrides.css', 'components/Button.css'];
const result = postcss.root();
for (const source of sources) {
  const root = postcss.parse(await readFile(new URL(`../src/${source}`, import.meta.url), 'utf8'));
  const animations = new Map();
  root.walkAtRules(/keyframes$/, rule => {
    const original = rule.params;
    if (original.startsWith('editor-')) { rule.remove(); return; }
    animations.set(original, `ntable-${original}`);
    rule.params = `ntable-${original}`;
  });
  root.walkDecls(/^animation(?:-name)?$/, declaration => {
    for (const [original, scoped] of animations) {
      declaration.value = declaration.value.replace(new RegExp(`\\b${original}\\b`, 'g'), scoped);
    }
  });
  root.walkRules(rule => {
    if (rule.parent.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
    const selectors = rule.selectors.filter(selector => !demoClass.test(selector.trim()) && !/^(?:html|body|#root)(?:$|[\s,:.#])/.test(selector.trim()));
    if (!selectors.length) { rule.remove(); return; }
    rule.selectors = selectors.flatMap(selector => {
      if (selector === ':root') {
        // The demo page background is not a component theme.
        rule.walkDecls('background', declaration => declaration.remove());
        return [scope];
      }
      return selector.startsWith('.') ? [`${scope}${selector}`, `${scope} ${selector}`] : [`${scope} ${selector}`];
    });
  });
  root.walkAtRules(rule => { if (rule.nodes && !rule.nodes.length) rule.remove(); });
  result.append(...root.nodes);
}
result.prepend(postcss.parse(`${scope}{font-size:14px;line-height:20px;-webkit-font-smoothing:antialiased}${scope},${scope} *{box-sizing:border-box}${scope} :focus-visible{outline:2px solid var(--blue);outline-offset:2px}`));
await writeFile(new URL('../src/ntable/library.css', import.meta.url), `/* Generated by scripts/build-library-css.mjs. Do not edit directly. */\n${result.toString()}\n`);
