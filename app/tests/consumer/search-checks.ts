/** UI-invoked regression harness. Exercises real React handlers, not the OS IME. */
export async function checkSearchInput(root: HTMLElement, events: () => string[]) {
  const wait = (ms: number) => new Promise(resolve => setTimeout(resolve, ms));
  const results: string[] = [];
  const assert = (ok: boolean, message: string) => { if (!ok) throw new Error(message); results.push(message); };
  let input = root.querySelector<HTMLInputElement>('input[aria-label="搜索记录"]')!;
  if (!input) throw new Error('请先打开搜索输入框');
  const setter = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')!.set!;
  const change = (text: string, composing = false) => {
    setter.call(input, text);
    input.dispatchEvent(new InputEvent('input', { bubbles: true, inputType: 'insertText', data: text, isComposing: composing }));
  };
  const initialCount = events().length;
  change('a'); change('ab'); change('abc');
  await wait(100);
  assert(input.value === 'abc' && events().length === initialCount, '输入立即回显，防抖前不提交');
  await wait(280);
  assert(events().length === initialCount + 1 && events().at(-1) === 'abc', '快速连续输入只提交最终值');
  change('pending');
  input.dispatchEvent(new CompositionEvent('compositionstart', { bubbles: true, data: '' }));
  change('zhong', true);
  await wait(380);
  assert(input.value === 'zhong' && events().length === initialCount + 1, '组词取消待提交搜索且不搜索拼音');
  change('中文', true);
  input.dispatchEvent(new CompositionEvent('compositionend', { bubbles: true, data: '中文' }));
  change('中文');
  await wait(100);
  assert(events().length === initialCount + 1, '组词结束后仍等待防抖');
  await wait(280);
  assert(events().length === initialCount + 2 && events().at(-1) === '中文', '组词结束只提交一次完整文字');
  change('');
  await wait(20);
  assert(events().at(-1) === '', '手动清空立即生效');
  change('cancel-me');
  root.querySelector<HTMLButtonElement>('button[aria-label="关闭搜索"]')!.click();
  await wait(380);
  assert(events().at(-1) === '' && !events().includes('cancel-me'), '关闭搜索取消待提交值');
  assert(document.activeElement === root.querySelector('button[aria-label="搜索"]'), '关闭搜索恢复触发器焦点');
  root.querySelector<HTMLButtonElement>('button[aria-label="搜索"]')!.click();
  await wait(20);
  input = root.querySelector<HTMLInputElement>('input[aria-label="搜索记录"]')!;
  change('disabled-pending');
  root.querySelector<HTMLButtonElement>('[data-probe-search-toggle]')!.click();
  await wait(20);
  root.querySelector<HTMLButtonElement>('[data-probe-search-toggle]')!.click();
  await wait(380);
  input = root.querySelector<HTMLInputElement>('input[aria-label="搜索记录"]')!;
  assert(input.value === '' && !events().includes('disabled-pending'), '回调移除再恢复不复活待提交查询');
  change('external-reset');
  Array.from(root.querySelectorAll('button')).find(button => button.textContent === '外部清空')!.click();
  await wait(380);
  assert(input.value === '' && !events().includes('external-reset'), '同值外部重置取消待提交草稿');
  change('unmounted');
  root.querySelector<HTMLButtonElement>('[data-probe-unmount]')!.click();
  await wait(380);
  assert(!events().includes('unmounted'), '组件卸载取消待提交查询');
  root.querySelector<HTMLButtonElement>('[data-probe-unmount]')!.click();
  return results;
}
